const interpretationSchema = z.object({
  // Numeric findings are rendered from resultFacts, never regenerated by a model.
  // The answer is cleaned sentence by sentence after generation instead of
  // rejecting the whole explanation when the model mentions a number.
  answer: z.string().min(1).max(120),
  suggestions: z.array(z.string().min(1).max(100)).max(3),
});
type Options = PlanningOptions & {
  onExecution?: (plan: AnalysisPlan | null) => void;
  onStep?: (step: import("./chat-types").AnalysisStep) => void;
};
type Dependencies = Partial<typeof toolQueries> & {
  generate: (
    question: string,
    instructions: string,
    schema: z.ZodObject<z.ZodRawShape>,
    options?: PlanningOptions,
    endpoint?: string,
    maxTokens?: number,
    parseResponse?: (value: unknown) => z.infer<typeof conversationDecisionSchema>,
  ) => Promise<{ fields: unknown; usedModel: string }>;
  analyze: typeof runAnalysis;
  distribution: typeof scoreDistribution;
};
const defaults: Dependencies = {
  generate: generateStructured,
  analyze: runAnalysis,
  distribution: scoreDistribution,
};
const number = (value: number) => value.toLocaleString("zh-CN", { maximumFractionDigits: 2 });

function assertActive(options: Options) {
  if (options.signal?.aborted) throw new QueryExecutionError("CANCELLED", "分析请求已取消。");
}

export function resultFacts(artifact: ChatArtifact): string[] {
  if (artifact.kind !== "analysis" && artifact.kind !== "distribution") return toolFacts(artifact);
  if (artifact.kind === "analysis") {
    const { result, plan } = artifact;
    const rows = [...result.rows].sort((a, b) => b.value - a.value);
    if (!rows.length) return ["当前筛选没有达到样本要求的统计结果；这不表示指标为零。"];
    return [
      `本次返回 ${rows.length} 个分组，最多返回 ${plan.limit} 个；仅展示至少 ${result.minSampleSize} 人的分组。`,
      `返回分组中最高：${rows[0].dimension}，${result.metricLabel} ${number(rows[0].value)} ${result.unit}，参与统计 ${number(rows[0].sampleSize)} 人。`,
      ...(rows.length > 1
        ? [
            `返回分组中最低：${rows.at(-1)!.dimension}，${number(rows.at(-1)!.value)} ${result.unit}；高低差 ${number(rows[0].value - rows.at(-1)!.value)} ${result.unit === "%" ? "个百分点" : result.unit}。`,
          ]
        : []),
      "各组样本可能重叠，人数不能直接相加；汇总差异不能证明原因或评价个体。",
    ];
  }
  const rows = distributionRows(
    artifact.data.groups,
    artifact.term,
    artifact.course,
    artifact.binWidth,
  );
  if (!rows.length) return ["当前筛选没有达到样本要求的成绩分布；这不表示无人学习或成绩为零。"];
  return [
    `本次展示 ${rows.length} 门课程，按 ${artifact.binWidth} 分一档；${artifact.term ? `学期 ${artifact.term}` : "全部学期，跨学期分别计次"}。`,
    ...rows.slice(0, 4).map((row) => {
      const peak = Math.max(...row.bins);
      const indices = row.bins.flatMap((count, index) => (count === peak ? [index] : []));
      return `${row.course}：有效成绩 ${number(row.count)} ${artifact.term ? "人" : "人次"}；${indices.length > 1 ? "并列最多分数段之一" : "最多的分数段"}为 ${scoreInterval(indices[0], artifact.binWidth)}，${number(peak)} ${artifact.term ? "人" : "人次"}，占 ${((peak / row.count) * 100).toFixed(1)}%。`;
    }),
    `只统计有效成绩，先按学生、课程、学期取均值；不足 ${artifact.data.minSampleSize} 人的课程学期分组已排除，缺失值不作零分。`,
  ];
}

function intentForGolden(input: ChatInput): ChatIntent | null {
  const golden = findGoldenCase(input.question);
  if (!golden) return null;
  const plan = planForDataset(golden, input.datasetId);
  // Exact presets remain standalone questions, even in an ongoing conversation.
  return {
    kind: "analysis",
    metric: plan.metric,
    dimension: plan.dimensions[0],
    filters: plan.filters,
    sort: plan.sort,
    limit: plan.limit,
    view: plan.chartType,
  };
}

function intentForFollowup(input: ChatInput): ChatIntent | null {
  if (!input.context) return null;
  const question = input.question.replace(/[。！？?\s]/g, "");
  if (/^(改成|换成|用|切换到?)表格(展示|显示)?$/.test(question))
    return { ...input.context, view: "table" };
  if (
    input.context.kind === "tool" &&
    /^(?:改成|换成|用|切换到?)(?:图表|图形|原图)(?:展示|显示)?$/.test(question)
  )
    return { ...input.context, view: "chart" };
  if (input.context.kind === "analysis") {
    if (/^(?:改成|换成|用)(?:图表|图形)(?:展示|显示)?$/.test(question))
      return { ...input.context, view: input.context.dimension === "term" ? "line" : "bar" };
    const view = /^(?:改成|换成|用)?(?:柱状图|条形图)$/.test(question)
      ? "bar"
      : /^(?:改成|换成|用)?折线图$/.test(question)
        ? "line"
        : /^(?:改成|换成|用)?(?:饼图|环形图)$/.test(question)
          ? "pie"
          : null;
    if (view) return { ...input.context, view };
  }
  if (input.context.kind === "distribution") {
    const match = question.match(/^(?:改成|改为|按)?(2|5|10)分一档$/);
    if (match) return { ...input.context, binWidth: Number(match[1]) as 2 | 5 | 10 };
    if (/^(改成|换成|用)热力图(展示|显示)?$/.test(question))
      return { ...input.context, view: "heatmap" };
  }
  return null;
}

export async function converse(
  raw: unknown,
  options: Options = {},
  dependencies: Dependencies = defaults,
): Promise<ChatResponse> {
  assertActive(options);
  const parsed = chatInputSchema.parse(raw);
  if (parsed.mode === "comprehensive") {
    const { converseComprehensive } = await import("./comprehensive");
    return converseComprehensive(parsed, options);
  }
  // Keep the quick planner's existing wire input unchanged.
  const { mode: _mode, ...input } = parsed;
  try {
    // Planning and explanation share the configured per-request cap.
    options = { ...options, budgetContext: { spent: 0 } };
    let goal = inferGoal(input.question);
    const followup = intentForFollowup(input);
    let intent = followup ?? intentForGolden(input);
    let planning: ChatResponse["planning"] = {
      source: followup ? "local" : "golden_case",
      rationale: followup ? "沿用上一轮筛选并调整展示。" : "使用已验证的常用分析计划。",
      model: null,
    };
    let distribution: Awaited<ReturnType<typeof scoreDistribution>> | undefined;

    if (!intent) {
      // Send only group labels to the planner. Student records and identifiers never enter prompts.
      let catalogFailure: unknown;
      try {
        distribution = await dependencies.distribution(input.datasetId, options);
      } catch (error) {
        assertActive(options);
        catalogFailure = error;
      }
      assertActive(options);
      const catalog = {
        available: !catalogFailure,
        courses: [...new Set(distribution?.groups.map((group) => group.course) ?? [])].sort(),
        terms: [...new Set(distribution?.groups.map((group) => group.term) ?? [])].sort(),
      };
      const comparison =
        /提升|提高.*多少|变化幅度|差值|下降.*多少|增幅/.test(input.question) &&
        (/成绩|均分|平均分/.test(input.question) ||
          (input.context?.kind === "analysis" && input.context.metric === "score"));
      const directTool = inferChartTool(input) ?? (comparison ? "dumbbell" : undefined);
      if (directTool) {
        if (catalogFailure) throw catalogFailure;
        intent = makeToolIntent(input, catalog, directTool);
        planning = {
          source: "local",
          rationale: "使用已有统计工具直接生成所请求的图表。",
          model: null,
        };
      } else {
        const generated = await dependencies.generate(
          JSON.stringify({ ...input, catalog }),
          CHAT_PLANNING_PROMPT,
          conversationDecisionSchema,
          options,
          "chat-plan",
          1100,
          parseConversationDecision,
        );
        // Model decisions keep their meaning. resolvePlan only fills blanks and
        // repairs contradictions; it never rewrites an action from question text.
        const resolved = resolvePlan(
          parseConversationDecision(generated.fields),
          input.question,
          input.context,
        );
        goal = resolved.goal;
        const decision = resolved.decision;
        planning = {
          source: getAIConfig().baseUrl ? "external" : "openai",
          rationale: decision.message || "按问题选择真实统计与原生图表。",
          model: generated.usedModel,
        };
        assertActive(options);
        if (decision.action === "reply" || decision.action === "clarify") {
          return {
            kind: decision.action === "reply" ? "answer" : "clarification",
            presentation: "text",
            answer:
              decision.message.trim().slice(0, 240) ||
              "你想查看哪个指标或图表？可以直接说明课程、学期与比较目标。",
            facts: [],
            suggestions: [],
            context: input.context,
            artifact: null,
            planning,
          };
        }
        if (catalogFailure) {
          options.onExecution?.(null);
          throw catalogFailure;
        }
        if (decision.action === "tool") {
          if (!decision.tool)
            throw new ChartClarification("请说明想比较、看分布、看趋势还是看关联，以便选择图表。");
          intent = makeToolIntent(input, catalog, decision.tool, decision);
        } else {
          const courses = selectedScope(
            input,
            "course",
            catalog,
            decision.courses ?? (decision.course ? [decision.course] : null),
          );
          let terms = selectedScope(
            input,
            "term",
            catalog,
            decision.terms ?? (decision.term ? [decision.term] : null),
          );
          if (
            goal === "trend" &&
            !catalog.terms.some((term) => input.question.includes(term)) &&
            !/最新|当前学期|本学期|上学期/.test(input.question)
          )
            terms = [];
          if (
            courses.some((c) => !catalog.courses.includes(c)) ||
            terms.some((t) => !catalog.terms.includes(t))
          )
            throw new ChartClarification("没有找到对应的课程或学期，请使用数据中的完整名称。");
          const course = courses[0] ?? "";
          const term = terms[0] ?? "";
          if (decision.action === "distribution" && (courses.length > 1 || terms.length > 1))
            throw new ChartClarification(
              "成绩分布目前支持单门或全部课程、单个或全部学期。比较指定多门课可使用箱线图，比较两学期均分可使用哑铃图。",
            );
          const previous = input.context;
          const previousAnalysis = previous?.kind === "analysis" ? previous : null;
          const dual = /每门.*每个学期|(?:课程.*学期|学期.*课程).*(?:分组|维度)/.test(
            input.question,
          );
          const dimensions: AnalysisPlan["dimensions"] | undefined = dual
            ? ["course", "term"]
            : (decision.dimensions ?? previousAnalysis?.dimensions);
          const dimension =
            dimensions?.[0] ?? decision.dimension ?? previousAnalysis?.dimension ?? "course";
          const filters = [
            ...(courses.length
              ? [
                  {
                    field: "course",
                    op: courses.length === 1 ? "eq" : "in",
                    value: courses.length === 1 ? courses[0] : courses,
                  },
                ]
              : []),
            ...(terms.length
              ? [
                  {
                    field: "term",
                    op: terms.length === 1 ? "eq" : "in",
                    value: terms.length === 1 ? terms[0] : terms,
                  },
                ]
              : []),
          ];
          intent = chatIntentSchema.parse(
            decision.action === "distribution"
              ? {
                  kind: "distribution",
                  course,
                  term,
                  binWidth:
                    decision.binWidth ??
                    (previous?.kind === "distribution" ? previous.binWidth : 5),
                  view:
                    decision.view ??
                    (previous?.kind === "distribution"
                      ? previous.view
                      : previous?.view === "table"
                        ? "table"
                        : "heatmap"),
                }
              : {
                  kind: "analysis",
                  metric: decision.metric ?? previousAnalysis?.metric,
                  dimension,
                  ...(dimensions ? { dimensions } : {}),
                  filters,
                  sort: {
                    by:
                      decision.sortBy ??
                      (previousAnalysis && dimension === previousAnalysis.dimension
                        ? previousAnalysis.sort.by
                        : dimension === "term"
                          ? "dimension"
                          : "value"),
                    direction:
                      decision.sortDirection ??
                      (previousAnalysis && dimension === previousAnalysis.dimension
                        ? previousAnalysis.sort.direction
                        : dimension === "term"
                          ? "asc"
                          : "desc"),
                  },
                  limit: Number(
                    input.question.match(
                      /(?:前|最多|只(?:展示|显示))\s*(\d{1,3})\s*(?:门|个|条|项)?/,
                    )?.[1] ?? 100,
                  ),
                  view: chooseAnalysisView(
                    input.question,
                    dimension,
                    decision.view === "heatmap" ? null : decision.view,
                    input.context,
                    goal,
                    dimensions,
                  ),
                },
          );
        }
      }
    }

    assertActive(options);
    let artifact: ChatArtifact;
    let warning: string | undefined;
    if (intent.kind === "tool") {
      options.onExecution?.(null);
      artifact = await executeChartTool(intent, input, options, dependencies);
    } else if (intent.kind === "analysis") {
      const plan = analysisPlanSchema.parse({
        version: 1,
        datasetId: input.datasetId,
        metric: intent.metric,
        aggregation: metricAggregation(intent.metric),
        dimensions: intent.dimensions ?? [intent.dimension],
        filters: intent.filters,
        sort: intent.sort,
        limit: intent.limit,
        chartType: intent.view === "line" ? "line" : intent.view === "table" ? "table" : "bar",
      });
      options.onExecution?.(plan);
      const analysis = await dependencies.analyze(plan, options);
      const reason = chartUnavailableReason(
        intent.view,
        analysis.result.unit,
        analysis.result.rows,
      );
      if (reason) {
        warning = `${reason} 已改用柱状图，仍可查看数值表。`;
        intent = { ...intent, view: "bar" };
      }
      artifact = { kind: "analysis", ...analysis, view: intent.view };
    } else {
      options.onExecution?.(null);
      distribution ??= await dependencies.distribution(input.datasetId, options);
      // Only return groups selected by the resolved intent.
      const selection = intent;
      artifact = {
        ...selection,
        data: {
          ...distribution,
          groups: distribution.groups.filter(
            (group) =>
              (!selection.course || group.course === selection.course) &&
              (!selection.term || group.term === selection.term),
          ),
        },
      };
    }
    assertActive(options);
    const facts = resultFacts(artifact);
    const presentation = responsePresentation(input.question, artifact, goal);
    const narrative = resultNarrative(artifact, goal, input.question);
    let answer = narrative;
    const suggestions =
      presentation === "text"
        ? ["改成图表", "改成表格"]
        : intent.kind === "tool"
          ? [intent.view === "table" ? "改成图表" : "改成表格"]
          : intent.kind === "distribution"
            ? ["改成表格", "按10分一档"]
            : ["改成表格", "按学期比较"];
    if (
      (planning.source === "openai" || planning.source === "external") &&
      (artifact.kind === "analysis" || artifact.kind === "distribution") &&
      /解读|为什么|原因|意味着|解释.{0,8}(?:结果|数据|差异)/.test(input.question)
    ) {
      try {
        const evidence =
          artifact.kind === "analysis"
            ? {
                metric: artifact.result.metricLabel,
                unit: artifact.result.unit,
                rows: artifact.result.rows,
              }
            : {
                rows: distributionRows(
                  artifact.data.groups,
                  artifact.term,
                  artifact.course,
                  artifact.binWidth,
                ),
              };
        const explanation = await dependencies.generate(
          JSON.stringify({
            question: input.question,
            history: input.history,
            intent,
            facts,
            evidence,
          }),
          CHAT_EXPLANATION_PROMPT,
          interpretationSchema,
          options,
          "chat-explain",
          350,
        );
        const explanationFields = interpretationSchema.parse(explanation.fields);
        // Verified numbers come from resultFacts. Drop only the model sentences
        // that carry a digit/percent and keep the rest of the prose; degrade to
        // the notice below only when nothing survives.
        const cleanedAnswer = sanitizeExplanation(explanationFields.answer);
        if (cleanedAnswer) {
          answer = `${narrative}\n${cleanedAnswer}`;
        } else {
          warning = [warning, "AI 解读暂未完成，已保留真实统计与数值表；可稍后继续追问。"]
            .filter(Boolean)
            .join(" ");
        }
        // Followups come from executable actions, not unconstrained model text.
      } catch (error) {
        // A failed explanation never discards a successful, verifiable query.
        assertActive(options);
        warning = [warning, "AI 解读暂未完成，已保留真实统计与数值表；可稍后继续追问。"]
          .filter(Boolean)
          .join(" ");
        if (error instanceof QueryExecutionError && error.code === "CANCELLED") throw error;
      }
    }
    assertActive(options);
    return {
      kind: "result",
      presentation,
      answer,
      facts,
      suggestions,
      context: intent,
      artifact,
      // The quick path shares the same result contract as the unified path,
      // including dropping facts that cite a result this response lacks.
      ...(() => {
        const described = describeResponseArtifacts([artifact], input.datasetId);
        if (described.warning) warning = [warning, described.warning].filter(Boolean).join(" ");
        return { resultRefs: described.resultRefs, factRefs: described.factRefs };
      })(),
      planning,
      ...(warning ? { warning } : {}),
    };
  } catch (error) {
    assertActive(options);
    if (!(error instanceof ChartClarification)) throw error;
    return {
      kind: "clarification",
      presentation: "text",
      answer: error.message,
      facts: [],
      suggestions: [],
      context: input.context,
      artifact: null,
      planning: { source: "local", rationale: "需要补充或调整查询范围。", model: null },
    };
  }
}
